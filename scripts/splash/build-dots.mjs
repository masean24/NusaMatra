/**
 * Indonesia as a grid of dots for the opening splash, written to src/features/intro/splashDots.ts so
 * the browser never loads world-atlas. Run once; the output is committed.
 *
 *   node scripts/splash/build-dots.mjs
 *   npx prettier --write src/features/intro/splashDots.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { geoContains, geoMercator, geoPath } from 'd3-geo';
import { feature } from 'topojson-client';

const OUTPUT = fileURLToPath(new URL('../../src/features/intro/splashDots.ts', import.meta.url));
const INDONESIA_ID = '360';
const WIDTH = 1060;
const HEIGHT = 440;
const GRID = 8.6;
const GRID_START = 20;
const SMALL_ISLAND = 1.6 * GRID;

const require = createRequire(import.meta.url);
const world = JSON.parse(readFileSync(require.resolve('world-atlas/countries-50m.json'), 'utf8'));
const land = feature(world, world.objects.countries).features.find(({ id }) => id === INDONESIA_ID);
if (!land) throw new Error(`Country ${INDONESIA_ID} is not in world-atlas`);

const projection = geoMercator().fitExtent(
  [
    [30, 30],
    [1030, 410],
  ],
  {
    type: 'MultiPoint',
    coordinates: [
      [95, 6],
      [141, -11],
    ],
  },
);
const path = geoPath(projection);

const onLand = (x, y) => {
  const lonLat = projection.invert([x, y]);
  return lonLat !== null && geoContains(land, lonLat);
};
const round = (value) => Number(value.toFixed(1));

const dots = [];
for (let y = GRID_START; y < HEIGHT; y += GRID) {
  for (let x = GRID_START; x < WIDTH; x += GRID) {
    if (!onLand(x, y)) continue;
    const coast = [
      [x + GRID, y],
      [x - GRID, y],
      [x, y + GRID],
      [x, y - GRID],
    ].some(([nx, ny]) => !onLand(nx, ny));
    dots.push([round(x), round(y), coast ? 1 : 0]);
  }
}
const gridCount = dots.length;

// An island smaller than the grid can fall between its points; it still gets one dot.
for (const coordinates of land.geometry.coordinates) {
  const polygon = { type: 'Polygon', coordinates };
  const [[left, top], [right, bottom]] = path.bounds(polygon);
  if (right - left >= SMALL_ISLAND || bottom - top >= SMALL_ISLAND) continue;
  const [x, y] = path.centroid(polygon);
  // Unless a dot already stands there: two on one spot only read as a blot.
  if (dots.some(([dotX, dotY]) => Math.hypot(dotX - x, dotY - y) < GRID / 2)) continue;
  dots.push([round(x), round(y), 1]);
}

const rows = dots.map((dot) => `  [${dot.join(', ')}],`).join('\n');
writeFileSync(
  OUTPUT,
  `// Generated by scripts/splash/build-dots.mjs from world-atlas countries-50m. Do not edit by hand.

/** The dots' coordinate space. */
export const SPLASH_MAP_WIDTH = ${String(WIDTH)};
export const SPLASH_MAP_HEIGHT = ${String(HEIGHT)};

/** Indonesia's dots as [x, y, coast]; coast is 1 when a neighbour on the grid is sea. */
export const SPLASH_DOTS: readonly (readonly [number, number, number])[] = [
${rows}
];
`,
);
console.log(`${String(gridCount)} grid dots + ${String(dots.length - gridCount)} small islands`);
